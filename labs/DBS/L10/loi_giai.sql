CREATE TABLE R(id INT, k INT); CREATE TABLE S(k INT, v INT);
WITH RECURSIVE c(x) AS (SELECT 1 UNION ALL SELECT x+1 FROM c WHERE x<200) INSERT INTO R SELECT x, ((x-1)%50)+1 FROM c;
WITH RECURSIVE c(x) AS (SELECT 1 UNION ALL SELECT x+1 FROM c WHERE x<50) INSERT INTO S SELECT x, x FROM c;
CREATE INDEX idx_sk ON S(k);
SELECT 'joined_rows=' || COUNT(*) FROM R JOIN S ON R.k=S.k;
SELECT 'idx_sk_ok=' || COUNT(*) FROM sqlite_master WHERE name='idx_sk';
SELECT 'sum_v=' || SUM(S.v) FROM R JOIN S ON R.k=S.k;
