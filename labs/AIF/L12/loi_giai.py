u = [0.0, 0.0, 1.0]
for _ in range(30):
    act1 = -0.05 + 0.9 * (0.7 * u[2] + 0.3 * u[1])
    act2 = -0.05 + 0.9 * (0.7 * u[0] + 0.3 * u[1])
    u1_new = max(act1, act2)
    u0_new = max(-0.05 + 0.9 * (0.7 * u[1] + 0.3 * u[0]), -0.05 + 0.9 * u[0])
    u[0], u[1] = u0_new, u1_new
print(f"U0={u[0]:.3f} U1={u[1]:.3f}")
