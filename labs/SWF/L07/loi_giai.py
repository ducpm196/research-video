def inord(n): return [] if not n else inord(n[1]) + [n[0]] + inord(n[2])
bst = (7, (5, (2, None, None), None), (9, None, (12, None, None)))
seq = inord(bst); b_ok = all(seq[i] < seq[i+1] for i in range(len(seq)-1))
def is_heap(h): return all(h[i] <= h[c] for i in range(len(h)) for c in (2*i+1, 2*i+2) if c < len(h))
print(f'bst_inorder_sorted={int(b_ok)}')
print(f'valid_heap={int(is_heap([1,4,3,7,8]))}')
print(f'broken_heap={int(is_heap([1,5,3,2,8]))}')
