import torch, torch.nn as nn
torch.manual_seed(42)
X = torch.tensor([[0.,0.],[0.,1.],[1.,0.],[1.,1.]] * 25)
y = torch.tensor([0, 1, 1, 0] * 25)
net = nn.Sequential(nn.Linear(2, 16), nn.ReLU(), nn.Linear(16, 2))
opt = torch.optim.Adam(net.parameters(), lr=0.05); crit = nn.CrossEntropyLoss()
for _ in range(150): opt.zero_grad(); loss = crit(net(X), y); loss.backward(); opt.step()
net.eval()
with torch.no_grad(): acc_mlp = (net(X[:4]).argmax(1) == y[:4]).float().mean().item()
torch.manual_seed(42)
lin = nn.Sequential(nn.Linear(2, 16), nn.Linear(16, 2))
opt2 = torch.optim.SGD(lin.parameters(), lr=0.1)
for _ in range(200): opt2.zero_grad(); l2 = crit(lin(X[:4]), y[:4]); l2.backward(); opt2.step()
with torch.no_grad(): acc_lin = (lin(X[:4]).argmax(1) == y[:4]).float().mean().item()
print(f'n_params={sum(p.numel() for p in net.parameters())}')
print(f'mlp_xor_acc={acc_mlp:.2f}')
print(f'no_relu_xor_acc={acc_lin:.2f}')
