WHENEVER SQLERROR EXIT FAILURE
SET SERVEROUTPUT ON
BEGIN EXECUTE IMMEDIATE 'DROP TABLE bnx_l07_lab_gd PURGE'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
CREATE TABLE bnx_l07_lab_gd (
  id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ngay DATE NOT NULL,
  tt VARCHAR2(400) CHECK (tt IS JSON (STRICT))
)
PARTITION BY RANGE (ngay) INTERVAL (NUMTOYMINTERVAL(1, 'MONTH')) (
  PARTITION p2025_01 VALUES LESS THAN (DATE '2025-02-01')
);

